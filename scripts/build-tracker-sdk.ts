/**
 * Builds the browser tracker SDK using esbuild and terser into
 * src/tracker/sdk.min.ts. Per-request settings are injected by the script
 * endpoint immediately before execution, so minification cannot pre-evaluate
 * privacy branches.
 */
import * as esbuild from "esbuild";
import { writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { minify } from "terser";
import { fileURLToPath } from "url";

import { createScriptLogger } from "./shared/logger";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const entry = resolve(root, "src/tracker/sdk.ts");

const rlog = createScriptLogger({
  logFile: "build-sdk.log",
});

function generateOutput(text: string): string {
  const escaped = JSON.stringify(text);
  return [
    `// Auto-generated by scripts/build-tracker-sdk.ts — DO NOT EDIT`,
    `// Source: src/tracker/sdk.ts (${new Date().toISOString()})`,
    `export const SDK_MIN = ${escaped};`,
    "",
  ].join("\n");
}

async function minifySdk(text: string): Promise<string> {
  const result = await minify(text, {
    ecma: 2020,
    compress: {
      passes: 2,
    },
    mangle: true,
    format: {
      comments: false,
    },
  });
  if (!result.code) {
    throw new Error("Terser produced empty output for the tracker SDK");
  }
  return result.code;
}

async function build() {
  rlog.info("Building tracker SDK...");
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    minify: false,
    format: "iife",
    target: ["es2020"],
    write: false,
  });
  const text = await minifySdk(result.outputFiles![0].text);
  writeFileSync(
    resolve(root, "src/tracker/sdk.min.ts"),
    generateOutput(text),
    "utf-8",
  );
  rlog.success(`  sdk.min.ts: ${(text.length / 1024).toFixed(2)} KB`);
}

build().catch((err) => {
  rlog.error("Failed to build tracker SDK:", err);
  process.exit(1);
});
